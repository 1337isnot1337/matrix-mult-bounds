"""Independent bit-convolution replay of the finite F2[S5] ideal certificate."""
from fractions import Fraction
import json
from pathlib import Path

from s5_source import group


def row_basis(rows):
    result = {}
    for value in rows:
        while value:
            pivot = value.bit_length()-1
            if pivot not in result:
                result[pivot] = value
                break
            value ^= result[pivot]
    return result


def reduce_row(value, basis):
    while value:
        pivot = value.bit_length()-1
        if pivot not in basis:
            return value
        value ^= basis[pivot]
    return 0


def multiply_matrix(A, B):
    result = 0
    for row in range(4):
        for column in range(4):
            parity = sum(((A >> (row+4*k)) & 1)*((B >> (k+4*column)) & 1)
                         for k in range(4)) % 2
            result |= parity << (row+4*column)
    return result


def multiply_group(G, left, right):
    result = 0
    while left:
        a = left & -left
        g = a.bit_length()-1
        rest = right
        while rest:
            b = rest & -rest
            result ^= 1 << G['mul'][g][b.bit_length()-1]
            rest ^= b
        left ^= a
    return result


def verify(report):
    G = group()
    if report['group'] != G['name'] or report['field'] != 'F2':
        raise ValueError('wrong modular group algebra')
    representations = report['representation_matrices']
    if len(representations) != 2 or any(len(rep) != 120 for rep in representations):
        raise ValueError('wrong representation format')
    for rep in representations:
        if any(type(value) is not int or not 0 <= value < 2**16 for value in rep):
            raise ValueError('invalid four-by-four binary matrix')
        for g in range(120):
            for h in range(120):
                if multiply_matrix(rep[g], rep[h]) != rep[G['mul'][g][h]]:
                    raise ValueError('representation product failed')
    constraints = [(1 << 120)-1]
    for rep in representations:
        constraints += [sum(1 << g for g in range(120) if rep[g] >> i & 1) for i in range(16)]
    image_rank = len(row_basis(constraints))
    powers = [[int(word, 16) for word in basis] for basis in report['power_bases']]
    dimensions = [120]+list(map(len, powers))
    if (dimensions != report['ideal_power_dimensions'] or dimensions[1] != 120-image_rank
            or report['kernel_dimension'] != dimensions[1]):
        raise ValueError('incorrect ideal/kernel dimensions')
    if any(v <= 0 or v >= 1 << 120 for basis in powers for v in basis):
        raise ValueError('invalid group-algebra coefficient vector')
    bases = [row_basis(basis) for basis in powers]
    if any(len(basis) != len(words) for basis, words in zip(bases, powers)):
        raise ValueError('dependent ideal-power basis')
    if any((r & v).bit_count() % 2 for r in constraints for v in powers[0]):
        raise ValueError('ideal generator is not in the representation kernel')
    products_checked = 0
    for index in range(1, len(powers)):
        product_basis = {}
        for left in powers[index-1]:
            for right in powers[0]:
                value = multiply_group(G, left, right)
                if reduce_row(value, bases[index]):
                    raise ValueError('product escapes the next ideal power')
                reduced = reduce_row(value, product_basis)
                if reduced:
                    product_basis[reduced.bit_length()-1] = reduced
                products_checked += 1
        if len(product_basis) != len(powers[index]):
            raise ValueError('next power is not fully generated by products')
    if bool(not powers[-1]) != report['nilpotent']:
        raise ValueError('incorrect nilpotence claim')
    layers = [dimensions[i]-dimensions[i+1] for i in range(len(dimensions)-1)]
    split = [0]*(len(layers)+1)
    for i, value in enumerate(layers):
        split[i] += value
        split[i+1] += value
    t = Fraction(report['parameter'])
    if not 0 < t < 1:
        raise ValueError('incorrect filtration parameter')
    Q = sum(value*t**i for i, value in enumerate(split))**3/t**(len(split)-1)
    if (layers != report['radical_layers'] or split != report['split_layers']
            or Q != Fraction(report['conditional_slice_bound_cubed'])
            or report['target_volume_squared'] != (13*14*14)**2
            or report['excludes_target_by_this_bound'] != ((13*14*14)**2 > Q)):
        raise ValueError('incorrect filtration count or target comparison')
    return {'image_rank': image_rank, 'kernel_dimension': dimensions[1],
            'power_dimensions': dimensions, 'group_products_checked': products_checked,
            'representation_products_checked': 28800,
            'target_excluded_by_this_bound': report['excludes_target_by_this_bound']}


if __name__ == '__main__':
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('report', type=Path)
    args = parser.parse_args()
    print(json.dumps(verify(json.loads(args.report.read_text())), indent=2))
